# Minimal key-based i18n for the console UI. Not gettext/.po/Flask-Babel
# -- this project only ever needs exactly two languages (see
# SUPPORTED_LANGS below), so a plain nested dict is simpler to read,
# grep, and diff than a compiled-catalog toolchain would be for a
# two-language app. See app.py's resolve_lang()/inject_user() for how
# the current request's language is picked and exposed to templates as
# the `t()` Jinja global, and base.html's language-toggle links for how
# a visitor changes it.
#
# Every template was originally Japanese-only; English entries were
# added afterward key-by-key, so `ja` is the authoritative fallback --
# translate() below falls back to `ja`, then to the bare key itself, so
# a missing `en` entry degrades to (readable, if not translated)
# Japanese rather than a raw key name or a KeyError.
