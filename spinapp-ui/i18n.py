def t(lang, key, **kwargs):
    """Look up `key` for `lang`, falling back to DEFAULT_LANG and then to
    the bare key itself (never raises -- a missing translation should be
    visible-but-ugly in the UI, not a 500)."""
    text = TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = TRANSLATIONS[DEFAULT_LANG].get(key, key)
    return text.format(**kwargs) if kwargs else text


def resolve_lang(cookie_value, accept_language_header):
    """cookie_value: the LANG_COOKIE_NAME cookie's raw value, or None.
    accept_language_header: the request's Accept-Language header, or None
    (kept as plain strings in/out, not a Flask Request, so this is
    trivially unit-testable and has no import-time Flask dependency).
    Cookie wins outright (an explicit choice, however it was made,
    always beats a header); otherwise best-match the browser's
    Accept-Language against SUPPORTED_LANGS; otherwise DEFAULT_LANG."""
    if cookie_value in SUPPORTED_LANGS:
        return cookie_value
    if accept_language_header:
        for part in accept_language_header.split(","):
            candidate = part.split(";")[0].strip().lower()
            if candidate in SUPPORTED_LANGS:
                return candidate
            # "en-US" etc. -- match on the primary subtag only.
            primary = candidate.split("-")[0]
            if primary in SUPPORTED_LANGS:
                return primary
    return DEFAULT_LANG
